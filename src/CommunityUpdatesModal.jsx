// Helper to get or persist official updates
export function getStoredOfficialUpdates() {
  try {
    const saved = localStorage.getItem('sidra_official_app_updates');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (e) {}
  return INITIAL_OFFICIAL_UPDATES;
}

export function saveOfficialUpdates(updatesList) {
  try {
    localStorage.setItem('sidra_official_app_updates', JSON.stringify(updatesList));
  } catch (e) {}
}

